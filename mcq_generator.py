# Expand with variations and more topics
def expand_dataset(base_mcqs, target_size=3000):
    """Expand dataset through repetition and slight variations."""
    expanded = []

    # First, add all base questions multiple times
    repetitions = target_size // len(base_mcqs) + 1
    for _ in range(repetitions):
        for mcq in base_mcqs:
            # Shuffle distractors for variety
            shuffled_mcq = mcq.copy()
            random.shuffle(shuffled_mcq["distractors"])
            expanded.append(shuffled_mcq)

    random.shuffle(expanded)
    return expanded[:target_size]

def create_dataset(mcq_data, train_ratio=0.85, val_ratio=0.10):
    """Create train/val/test splits."""

    def format_item(item):
        q = item["question"].strip()
        correct = item["correct"].strip()
        distractors = [d.strip() for d in item["distractors"]]

        # Always put correct answer first (position A)
        options = [correct] + distractors[:3]  # Ensure exactly 4 options

        labeled = [f"{chr(65+i)}) {opt}" for i, opt in enumerate(options)]

        text = (
            "Generate a multiple-choice question with exactly 4 options (A-D). "
            "Mark the correct answer.\n\n"
            f"Question: {q}\n" + "\n".join(labeled) + "\n\nCorrect Answer: A\n"
        )
        return {"text": text, "topic": item.get("topic", "General"), "question": q}

    # Split data
    random.shuffle(mcq_data)
    total = len(mcq_data)
    train_end = int(total * train_ratio)
    val_end = train_end + int(total * val_ratio)

    train_data = mcq_data[:train_end]
    val_data = mcq_data[train_end:val_end]
    test_data = mcq_data[val_end:]

    # Create datasets
    train_ds = Dataset.from_dict({"data": train_data})
    val_ds = Dataset.from_dict({"data": val_data})
    test_ds = Dataset.from_dict({"data": test_data})

    # Format
    train_ds = train_ds.map(lambda x: format_item(x["data"]), remove_columns=["data"])
    val_ds = val_ds.map(lambda x: format_item(x["data"]), remove_columns=["data"])
    test_ds = test_ds.map(lambda x: format_item(x["data"]), remove_columns=["data"])

    print(f"📊 Dataset splits — train: {len(train_ds)}, val: {len(val_ds)}, test: {len(test_ds)}")
    print(f"📝 Sample:\n{train_ds[0]['text'][:200]}...")

    # Save dataset info
    dataset_info = {
        "train_size": len(train_ds),
        "val_size": len(val_ds),
        "test_size": len(test_ds),
        "topics": list(set([item.get("topic", "General") for item in mcq_data])),
        "total_questions": len(mcq_data)
    }

    with open(f"{RESULTS_DIR}/dataset_info.json", "w") as f:
        json.dump(dataset_info, f, indent=2)

    return train_ds, val_ds, test_ds

