def train_model(model, tokenizer, train_ds, val_ds, output_dir=MODEL_DIR):
    """Train with proper tracking."""

    training_args = TrainingArguments(
        output_dir=output_dir,
        per_device_train_batch_size=4,
        per_device_eval_batch_size=4,
        gradient_accumulation_steps=2,  # Effective batch size = 8
        learning_rate=3e-4,
        num_train_epochs=5,
        logging_dir=f"{output_dir}/logs",
        logging_steps=25,
        eval_strategy="epoch",  # Changed from "steps" to match save_strategy
        save_strategy="epoch",
        save_total_limit=2,
        fp16=torch.cuda.is_available(),
        report_to="none",
        warmup_steps=200,
        weight_decay=0.01,
        load_best_model_at_end=True,
        metric_for_best_model="eval_loss",
    )

    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=train_ds,
        eval_dataset=val_ds,
        tokenizer=tokenizer,
        data_collator=default_data_collator,
    )

    print("🚀 Starting training...")
    train_result = trainer.train()

    # Save model and training info
    model.save_pretrained(output_dir)
    tokenizer.save_pretrained(output_dir)

    # Save training metrics
    training_metrics = {
        "train_runtime": train_result.metrics.get("train_runtime", 0),
        "train_loss": train_result.metrics.get("train_loss", 0),
        "epoch": train_result.metrics.get("epoch", 0),
        "total_steps": train_result.global_step,
    }

    with open(f"{RESULTS_DIR}/metrics/training_metrics.json", "w") as f:
        json.dump(training_metrics, f, indent=2)

    print(f"✅ Training complete! Saved to {output_dir}")
    return trainer

