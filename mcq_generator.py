class MCQGenerator:
    """Production-ready MCQ generator."""

    def __init__(self, base_model_name, adapter_path):
        print("🔄 Loading model...")
        self.tokenizer = AutoTokenizer.from_pretrained(base_model_name)
        if self.tokenizer.pad_token is None:
            self.tokenizer.add_special_tokens({"pad_token": self.tokenizer.eos_token})

        base_model = AutoModelForCausalLM.from_pretrained(
            base_model_name,
            device_map="auto",
            torch_dtype=torch.float16 if torch.cuda.is_available() else torch.float32
        )

        self.model = PeftModel.from_pretrained(base_model, adapter_path)
        self.model.eval()
        print("✅ Model loaded!")

    def generate(self, question, temperature=0.7, top_p=0.9, max_tokens=200):
        """Generate MCQ with error handling."""
        try:
            prompt = (
                f"Generate a multiple-choice question with exactly 4 options (A-D). "
                f"Mark the correct answer.\n\n"
                f"Question: {question}\nA) "
            )

            inputs = self.tokenizer(prompt, return_tensors="pt", truncation=True).to(self.model.device)

            with torch.no_grad():
                outputs = self.model.generate(
                    **inputs,
                    max_new_tokens=max_tokens,
                    temperature=temperature,
                    top_p=top_p,
                    repetition_penalty=1.2,
                    do_sample=True,
                    pad_token_id=self.tokenizer.eos_token_id,
                )

            text = self.tokenizer.decode(outputs[0], skip_special_tokens=True)
            generated = text.split("A) ")[-1] if "A) " in text else text.split(prompt)[-1]

            result = f"Question: {question}\nA) {generated}"

            # Parse and validate
            parsed = self.parse_mcq(result)
            if not parsed["has_all_options"]:
                return result + "\n\n⚠️ Note: Generation incomplete. Try again or adjust parameters."

            return result

        except Exception as e:
            return f"❌ Error generating MCQ: {str(e)}\nPlease try again."

    def parse_mcq(self, mcq_text):
        """Parse MCQ structure."""
        lines = [l.strip() for l in mcq_text.split('\n') if l.strip()]

        result = {
            "question": "",
            "options": {},
            "correct_answer": "",
            "has_all_options": False,
            "has_answer": False
        }

        for line in lines:
            if line.startswith("Question:"):
                result["question"] = line.replace("Question:", "").strip()
            elif len(line) > 0 and line[0] in "ABCD" and line[1:3] in [") ", ". "]:
                letter = line[0]
                option_text = line[3:].strip() if line[1] == ")" else line[2:].strip()
                result["options"][letter] = option_text
            elif "Correct Answer:" in line or "Answer:" in line:
                for char in line:
                    if char in "ABCD":
                        result["correct_answer"] = char
                        result["has_answer"] = True
                        break

        result["has_all_options"] = len(result["options"]) == 4
        return result

    def batch_generate(self, questions, temperature=0.7):
        """Generate multiple MCQs."""
        results = []
        for q in questions:
            mcq = self.generate(q.strip(), temperature=temperature)
            results.append(mcq)
        return results

