class MCQEvaluator:
    """Comprehensive MCQ evaluation."""

    def __init__(self, model, tokenizer):
        self.model = model
        self.tokenizer = tokenizer
        self.rouge_scorer = rouge_scorer.RougeScorer(['rouge1', 'rouge2', 'rougeL'], use_stemmer=True)
        self.smoothing = SmoothingFunction().method1

    def generate_mcq(self, question, max_new_tokens=200):
        """Generate MCQ for evaluation."""
        prompt = (
            f"Generate a multiple-choice question with exactly 4 options (A-D). "
            f"Mark the correct answer.\n\n"
            f"Question: {question}\nA) "
        )

        inputs = self.tokenizer(prompt, return_tensors="pt", truncation=True).to(self.model.device)

        with torch.no_grad():
            outputs = self.model.generate(
                **inputs,
                max_new_tokens=max_new_tokens,
                temperature=0.7,
                top_p=0.9,
                repetition_penalty=1.2,
                do_sample=True,
                pad_token_id=self.tokenizer.eos_token_id,
            )

        text = self.tokenizer.decode(outputs[0], skip_special_tokens=True)
        generated = text.split("A) ")[-1] if "A) " in text else text.split(prompt)[-1]

        return f"Question: {question}\nA) {generated}"

    def parse_mcq(self, mcq_text):
        """Parse MCQ into components."""
        lines = [l.strip() for l in mcq_text.split('\n') if l.strip()]

        result = {
            "question": "",
            "options": {},
            "correct_answer": "",
            "has_all_options": False,
            "has_answer": False
        }

        for line in lines:
            if line.startswith("Question:"):
                result["question"] = line.replace("Question:", "").strip()
            elif len(line) > 0 and line[0] in "ABCD" and line[1:3] in [") ", ". "]:
                letter = line[0]
                option_text = line[3:].strip() if line[1] == ")" else line[2:].strip()
                result["options"][letter] = option_text
            elif "Correct Answer:" in line or "Answer:" in line:
                for char in line:
                    if char in "ABCD":
                        result["correct_answer"] = char
                        result["has_answer"] = True
                        break

        result["has_all_options"] = len(result["options"]) == 4
        return result

    def evaluate_quality(self, generated_mcq, reference_question=None):
        """Evaluate MCQ quality."""
        parsed = self.parse_mcq(generated_mcq)

        scores = {
            "structural_validity": 0.0,
            "completeness": 0.0,
            "option_diversity": 0.0,
            "answer_clarity": 0.0,
        }

        # Structural validity
        if parsed["has_all_options"] and parsed["has_answer"]:
            scores["structural_validity"] = 1.0
        elif parsed["has_all_options"] or parsed["has_answer"]:
            scores["structural_validity"] = 0.5

        # Completeness
        if parsed["question"] and len(parsed["options"]) >= 3:
            scores["completeness"] = len(parsed["options"]) / 4.0

        # Option diversity (length variety)
        if len(parsed["options"]) >= 3:
            lengths = [len(opt.split()) for opt in parsed["options"].values()]
            scores["option_diversity"] = min(1.0, np.std(lengths) / 5.0)

        # Answer clarity
        if parsed["has_answer"] and parsed["correct_answer"] in parsed["options"]:
            scores["answer_clarity"] = 1.0

        # Overall score
        overall = np.mean(list(scores.values()))

        return {
            "scores": scores,
            "overall": overall,
            "parsed": parsed
        }

    def evaluate_test_set(self, test_dataset, num_samples=50):
        """Comprehensive test set evaluation."""
        print(f"\n📊 Evaluating on {num_samples} test samples...")

        results = []
        metrics = defaultdict(list)

        test_samples = random.sample(range(len(test_dataset)), min(num_samples, len(test_dataset)))

        for idx in test_samples:
            sample = test_dataset[idx]
            question = sample["question"]

            # Generate MCQ
            generated = self.generate_mcq(question)

            # Evaluate
            eval_result = self.evaluate_quality(generated)

            results.append({
                "question": question,
                "generated": generated,
                "evaluation": eval_result
            })

            # Aggregate metrics
            for metric_name, value in eval_result["scores"].items():
                metrics[metric_name].append(value)
            metrics["overall"].append(eval_result["overall"])

        # Calculate averages
        avg_metrics = {k: np.mean(v) for k, v in metrics.items()}

        # Save results
        evaluation_report = {
            "timestamp": datetime.now().isoformat(),
            "num_samples": num_samples,
            "average_metrics": avg_metrics,
            "detailed_results": results[:10],  # Save first 10 examples
            "summary": {
                "excellent": sum(1 for r in results if r["evaluation"]["overall"] >= 0.8),
                "good": sum(1 for r in results if 0.6 <= r["evaluation"]["overall"] < 0.8),
                "fair": sum(1 for r in results if 0.4 <= r["evaluation"]["overall"] < 0.6),
                "poor": sum(1 for r in results if r["evaluation"]["overall"] < 0.4),
            }
        }

        with open(f"{RESULTS_DIR}/metrics/evaluation_report.json", "w") as f:
            json.dump(evaluation_report, f, indent=2)

        print(f"\n✅ Evaluation complete!")
        print(f"📈 Average Overall Score: {avg_metrics['overall']:.3f}")
        print(f"   - Structural Validity: {avg_metrics['structural_validity']:.3f}")
        print(f"   - Completeness: {avg_metrics['completeness']:.3f}")
        print(f"   - Option Diversity: {avg_metrics['option_diversity']:.3f}")
        print(f"   - Answer Clarity: {avg_metrics['answer_clarity']:.3f}")

        return evaluation_report

